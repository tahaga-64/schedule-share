const pad = (n: number) => String(n).padStart(2, '0');

/** `year`・`month`(0始まり)・`day` を受け取り、祝日ならその名前、そうでなければ null を返す。 */
export const getHoliday = (year: number, month: number, day: number): string | null => {
  return JP_HOLIDAYS[`${year}-${pad(month + 1)}-${pad(day)}`] ?? null;
};

/** `YYYY-MM-DD` 文字列から祝日名を引く（null 可）。 */
export const getHolidayByDate = (dateStr: string): string | null => {
  return JP_HOLIDAYS[dateStr] ?? null;
};

/** 日曜または祝日なら true（赤表示の判定用）。month は 0 始まり。 */
export const isRedDay = (year: number, month: number, day: number): boolean => {
  const dow = new Date(year, month, day).getDay();
  return dow === 0 || getHoliday(year, month, day) !== null;
};
